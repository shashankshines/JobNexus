/**
 * Source Registry Helper Class
 * Provides sector-aware filtering, health tracking, and operational diagnostics.
 */
export class SourceRegistry {
  private static sources: Map<string, VerifiedSource> = new Map(
    VERIFIED_SOURCES.map((s) => [s.id, s])
  );

  static getAll(): VerifiedSource[] {
    return Array.from(this.sources.values());
  }

  static getActive(): VerifiedSource[] {
    return this.getAll().filter((s) => s.active);
  }

  static getItSources(): VerifiedSource[] {
    return this.getAll().filter((s) => s.category === 'it');
  }

  static getNonItSources(): VerifiedSource[] {
    return this.getAll().filter((s) => s.category === 'non_it');
  }

  static getById(id: string): VerifiedSource | undefined {
    return this.sources.get(id);
  }

  static getBySector(sector: string): VerifiedSource[] {
    const term = sector.toLowerCase();
    return this.getAll().filter(
      (s) => s.sector.toLowerCase().includes(term) || s.subsector?.toLowerCase().includes(term)
    );
  }

  static getStats(): {
    total: number;
    active: number;
    itCount: number;
    nonItCount: number;
    healthyCount: number;
    degradedCount: number;
    offlineCount: number;
    sectors: Record<string, number>;
  } {
    const all = this.getAll();
    const sectors: Record<string, number> = {};

    let itCount = 0;
    let nonItCount = 0;
    let healthyCount = 0;
    let degradedCount = 0;
    let offlineCount = 0;

    for (const source of all) {
      if (source.category === 'it') itCount++;
      else nonItCount++;

      if (source.healthStatus === 'healthy') healthyCount++;
      else if (source.healthStatus === 'degraded') degradedCount++;
      else offlineCount++;

      sectors[source.sector] = (sectors[source.sector] || 0) + 1;
    }

    return {
      total: all.length,
      active: all.filter((s) => s.active).length,
      itCount,
      nonItCount,
      healthyCount,
      degradedCount,
      offlineCount,
      sectors,
    };
  }
}

